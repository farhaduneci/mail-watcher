// Scans src/channels for channel files and writes src/channels/registry.ts, so adding a channel
// is one dropped-in file.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join(import.meta.dirname, "../src/channels/");
const SKIP = new Set(["types.ts", "registry.ts"]);

export function generateRegistry(): string[] {
  const names = readdirSync(DIR)
    .filter((f) => f.endsWith(".ts") && !SKIP.has(f) && !f.endsWith(".test.ts"))
    .map((f) => f.slice(0, -3))
    .sort();
  const ident = (n: string) => `channel_${n.replace(/\W/g, "_")}`;
  const source = [
    "// Generated by scripts/registry.ts from the files in this folder. Do not edit.",
    'import type { Channel } from "./types";',
    ...names.map((n) => `import ${ident(n)} from "./${n}";`),
    "",
    `export const CHANNELS: readonly Channel[] = [${names.map(ident).join(", ")}];`,
    "",
  ].join("\n");
  const path = `${DIR}registry.ts`;
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current !== source) writeFileSync(path, source);
  return names;
}
